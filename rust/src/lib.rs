//! Rust examples for the "Agentic AI & Creative Coding" workshop.
//!
//! There is no official Anthropic Rust SDK, so these demos use the
//! community-maintained [`claudius`](https://crates.io/crates/claudius) crate.
//!
//! The crate itself carries no library code; every demo lives as a standalone
//! file under `examples/`. Run one with, e.g.:
//!
//! ```sh
//! cargo run --example demo_010_hello_world
//! ```
